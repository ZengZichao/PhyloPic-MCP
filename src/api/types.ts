/**
 * Type definitions for the PhyloPic API v2 responses.
 * @module api/types
 */

/** A hyperlink with an href and optional title. */
export interface Link {
  href: string;
  title?: string;
}

/** A media link with additional metadata (sizes, type). */
export interface MediaLink extends Link {
  sizes?: string;
  type?: string;
}

/** A node name segment, either scientific or vernacular. */
export interface NodeNamePart {
  class: "scientific" | "vernacular" | "citation";
  text: string;
}

/** A node name is an array of name parts. */
export type NodeName = NodeNamePart[];

/** Links associated with a phylogenetic node. */
export interface NodeLinks {
  self: Link;
  childNodes?: Link[];
  cladeImages?: Link;
  external?: Link[];
  images?: Link;
  lineage?: Link;
  parentNode?: Link | null;
  primaryImage?: Link;
}

/** A phylogenetic node entity. */
export interface Node {
  uuid: string;
  build: number;
  created: string;
  names: NodeName[];
  _links: NodeLinks;
}

/** Links associated with a silhouette image. */
export interface ImageLinks {
  self: Link;
  contributor: Link;
  generalNode?: Link;
  specificNode: Link;
  nodes: Link[];
  license: Link;
  sourceFile?: MediaLink;
  vectorFile?: MediaLink;
  rasterFiles?: MediaLink[];
  thumbnailFiles?: MediaLink[];
  "http://ogp.me/ns#image"?: MediaLink;
}

/** A silhouette image entity. */
export interface Image {
  uuid: string;
  build: number;
  created: string;
  modified?: string;
  /** Attribution string generated by the API. */
  attribution?: string;
  /** Optional sponsor name for the image. */
  sponsor?: string | null;
  /** UUID of the file used for modification tracking. */
  modifiedFile?: string | null;
  _links: ImageLinks;
}

/** Links associated with a contributor. */
export interface ContributorLinks {
  self: Link;
  contact?: Link | null;
  images: Link;
}

/** A contributing user entity. */
export interface Contributor {
  uuid: string;
  build: number;
  created: string;
  modified?: string;
  name: string;
  count: number;
  _links: ContributorLinks;
}

/** Links returned for a page of results. */
export interface PageLinks {
  self: Link;
  firstPage?: Link;
  lastPage?: Link;
  nextPage?: Link;
  previousPage?: Link;
  /** Link array to each item on this page. */
  items?: Link[];
  /** Link to the full unfiltered list endpoint. */
  list?: Link;
}

/** A generic page response for paginated lists.
 *
 *  Note: PhyloPic's API does not always return `totalItems`/
 *  `totalPages`; instead it relies on `next`/`previous` links
 *  for navigation. The `index` field is always present when the
 *  page is valid.
 */
export interface Page<T> {
  build: number;
  index?: number;
  totalItems?: number;
  totalPages?: number;
  itemsPerPage?: number;
  _links: PageLinks;
  _embedded?: {
    items: T[];
  };
}

/** Autocomplete response. */
export interface AutocompleteResponse {
  build: number;
  matches: string[];
  _links: {
    self: Link;
  };
}

/** The API root/index response. */
export interface APIRoot {
  build: number;
  buildTimestamp: string;
  title: string;
  version: string;
  _links: {
    self: Link;
    contact: Link;
    documentation: Link;
    resources: Link[];
  };
}

/** A license available for new image submissions.
 *
 *  The /licenses endpoint returns a bare array of simple link
 *  objects (each with an `href` pointing to the Creative Commons
 *  license URL and an optional `title`). It is not a standard
 *  HAL entity.
 */
export interface License {
  href: string;
  title?: string;
}

/** An authorized external namespace. */
export interface AuthorizedNamespace {
  authority: string;
  namespace: string;
}

/** Response from /namespaces endpoint. */
export interface NamespacesResponse {
  build: number;
  namespaces: AuthorizedNamespace[];
}

/** Node with embedded entities. */
export interface NodeWithEmbedded extends Node {
  _embedded?: {
    parentNode?: Node;
    primaryImage?: Image;
  };
}

/** Image with embedded entities. */
export interface ImageWithEmbedded extends Image {
  _embedded?: {
    contributor?: Contributor;
    generalNode?: Node;
    specificNode?: Node;
    nodes?: Node[];
  };
}

/** A single error entry returned by the PhyloPic API. */
export interface ApiError {
  developerMessage: string;
  field?: string;
  type: string;
  userMessage: string;
}

/** Error response body from the PhyloPic API. */
export interface ApiErrorResponse {
  build: number;
  errors: ApiError[];
}

/** Query parameters for listing images. */
export interface ImageListParams {
  build?: number;
  page?: number;
  embed_items?: boolean;
  filter_node?: string;
  filter_clade?: string;
  filter_contributor?: string;
  filter_created_after?: string;
  filter_created_before?: string;
  filter_modified_after?: string;
  filter_modified_before?: string;
}

/** Query parameters for listing nodes. */
export interface NodeListParams {
  build?: number;
  page?: number;
  embed_items?: boolean;
  filter_name?: string;
  filter_created_after?: string;
  filter_created_before?: string;
}

/** Query parameters for listing contributors. */
export interface ContributorListParams {
  build?: number;
  page?: number;
  embed_items?: boolean;
}
